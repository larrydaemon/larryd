def view_of(job):
    """A JOB'S RULE AS THE PANELS SAY IT: the job as it is, with its review's two fields said as one line (who · when · VERDICT word · why)."""
    job = dict(job or {})
    verdict, said = str(job.get('data_job_rules_review_verdict') or ''), str(job.get('data_job_rules_review_description') or '')
    if verdict:   # the review, from its own two fields: who and when, the verdict, why
        who, _, why = said.partition(' · ')
        when, _, why = why.partition(' · ')
        job['data_job_rule_review'] = ' · '.join(x for x in (who, when) if x) + f' · VERDICT {verdict}' + (f' · {why}' if why else '')
    return job


