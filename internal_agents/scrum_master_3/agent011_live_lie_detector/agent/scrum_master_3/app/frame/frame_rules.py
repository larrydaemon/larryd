def read_one(agent, settings, app, file, raw, digest, job, module=None, hire_with=None, now=None):
    """ONE PROGRAM: GENERATE parts 2 to 4 (one read), then REVIEW them BLIND (a second, separate read). -> (fields or None, said)"""
    model = settings['models']['web']
    source = raw.decode('utf-8', errors='replace')
    green = [e for e in frame.job_skills(job) if e['state'] == 'green']
    run = hire_with or hire
    code, said = run(command(settings), generate_words(agent, file, source, job, green, knowledge_of(agent, module) if module else []), app, SECONDS, settings.get('reads', {}).get('job_path', ''))
    if code != 0:
        return None, f'not generated: the read stopped or did not answer (exit {code}): {one_line(said)[-160:]}'
    got = parts(said)
    if not got:
        return None, f'not generated: the read gave no FIX, RED and GREEN lines: {one_line(said)[-160:]}'
    code, said = run(command(settings), review_words(agent, file, source, {**job, **{'data_job_' + k: v for k, v in got.items()}}), app, SECONDS, settings.get('reads', {}).get('job_path', ''))
    if code != 0:
        return None, f'not reviewed: the read stopped or did not answer (exit {code}): {one_line(said)[-160:]}'
    verdict = answer(said)
    if not verdict:
        return None, f'not reviewed: the read gave no verdict line (VERDICT LEGIT or STUPID and why): {one_line(said)[-160:]}'
    at = said_at((now or datetime.datetime.now()).isoformat(timespec='seconds'))
    return ({**got, 'rules_review_verdict': verdict['verdict'], 'rules_review_description': f"{reviewer(model)} · {at} · {verdict['why']}",
             'rule_code': f'{file} · {digest}', 'lie_detector': 'CLEAN'},
            f"generated and reviewed · {digest[:12]} · {verdict['verdict']} · {verdict['why'][:90]}")


def read_chain(store, agent, settings, app, chain, hire_with=None, force=False, now=None):
    """EVERY AGENT OF THE CHAIN (SKILLS_POSITIVE_FEEDBACK_BUILD 3.1): part 1, the rule, is the system owner's and never written here, except that an
    empty job gets it once from his record of the original row (tuned by hand); an agent with neither has nothing to read. When the program's
    sha256 differs from the one kept (field 8), or no part is kept yet, or force: parts 2 to 4 are generated and then reviewed blind; else only
    the lie detector is said again. -> {'read', 'failed', 'unchanged', 'seeded', 'none', 'lines'}"""
    out = {'read': [], 'failed': {}, 'unchanged': 0, 'seeded': [], 'none': [], 'lines': []}
    facts = (agent or {}).get('facts') or {}
    records = old_records(facts)
    origin = os.path.dirname(os.path.dirname(os.path.abspath(os.path.expanduser(str(facts['db']))))) if facts.get('db') else ''
    office = os.path.dirname(os.path.abspath(app))
    for module, shell in chain:
        file = os.path.basename(module.__file__)
        path = os.path.join(app, 'agent', file)
        job, job_key = dict(shell['job'] or {}), shell['job_key']
        put = lambda vals, job_key=job_key: store.set_job(job_key, vals)
        state = {frame.SETTINGS['root_shape']['x_board']['done']: 'GREEN', 'FAILED': 'RED'}.get(str(job.get('data_job_run_state') or ''))
        if state and job.get('data_job_rules_status') != state:   # THE STATUS (field 2): the agent's own check, its last run ended DONE or FAILED; a run still going leaves it
            put({'rules_status': state})
            job['data_job_rules_status'] = state
        if not job.get('data_job_rule'):   # the owner's rule, once, from his record of the original row: the only time this tool writes part 1
            rec = records.get(getattr(module, 'ROW_FILE', '') or '')
            if not rec:
                out['none'].append(file)
                continue
            put({'rule': tune(rec['rule'], rec['row'], job.get('data_full_name') or (agent or {}).get('name') or '', office, origin), 'rules_status': NOT_READ})
            job['data_job_rule'] = tune(rec['rule'], rec['row'], job.get('data_full_name') or (agent or {}).get('name') or '', office, origin)
            out['seeded'].append(file)
        try:
            with open(path, 'rb') as fh:
                raw = fh.read()
        except OSError as e:
            out['failed'][file] = f'not read: its file could not be read ({type(e).__name__})'
            if job.get('data_job_lie_detector') != 'TAMPER':
                put({'lie_detector': 'TAMPER'})
            continue
        digest = sha(raw)
        have = kept(job)
        whole = all(job.get('data_job_' + f) for f in ('rule_fix', 'rule_red', 'rule_green', 'rules_review_verdict'))
        if not force and whole and have and have['sha'] == digest:
            out['unchanged'] += 1
            if job.get('data_job_lie_detector') != 'CLEAN':
                put({'lie_detector': 'CLEAN'})
            continue
        values, line = read_one(agent, settings, app, file, raw, digest, job, module, hire_with, now)
        if values:
            put(values)
            out['read'].append(file)
        else:
            out['failed'][file] = line
            word = detect(job, path)
            if job.get('data_job_lie_detector') != word:
                put({'lie_detector': word})
        out['lines'].append(f'{file}: {line}')
    return out


