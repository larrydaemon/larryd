def one_line(text):
    return ' '.join(str(text or '').replace('—', ', ').replace('–', '-').split())


def answer(said):
    """THE VERDICT, the answer's last VERDICT line: {'verdict': LEGIT or STUPID, 'why': one line}, or None when there is none or it
    gives no why: a verdict is never kept half said."""
    for line in reversed(str(said or '').splitlines()):
        m = VERDICT.match(line)
        if m:
            why = one_line(m.group(2))[:MOST]
            return {'verdict': m.group(1).upper(), 'why': why} if why else None
    return None


def parts(said):
    """THE GENERATOR'S PARTS, its FIX, RED and GREEN lines: {'rule_fix', 'rule_red', 'rule_green'}, or None unless all three are said."""
    got = {}
    for line in str(said or '').splitlines():
        m = PART.match(line)
        if m:
            got['rule_' + m.group(1).lower()] = one_line(m.group(2))[:1200]   # never cut mid sentence (Pick's and Build's RED were, 2026-10-28): a margin past the 900 it is asked for
    return got if len(got) == 3 else None


def said_at(moment):
    """A moment as the original says it: OCT 25 16:14."""
    try:
        return datetime.datetime.fromisoformat(moment).strftime('%b %d %H:%M').upper()
    except (TypeError, ValueError):
        return ''


def reviewer(by):
    """WHO REVIEWED, as the original says it: claude-opus-5-5 -> OPUS 5.5."""
    return (by or '').replace('claude-opus-5-5', 'Opus 5.5').upper()


