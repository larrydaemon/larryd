def rules_word(job):
    """THE WORD ON THE RULES BUTTON (the owner 2026-10-27; the original's label ends in its verdict): the reviewer's verdict, LEGIT or STUPID, read
    from the job's review line; before a read, the job's rules status (the species' default NOT READ YET). Nothing counted here."""
