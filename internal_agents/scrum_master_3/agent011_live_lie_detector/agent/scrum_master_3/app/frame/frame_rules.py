def old_records(facts):
    """HIS RECORD OF EVERY ROW'S RULE (the original's settings table, row_rules.row_NNN), read where it is, read only, from the original's database
    the office names (facts db): {the program each was read from: the record}; none when the office names none or it cannot be read."""
    db = os.path.expanduser(str((facts or {}).get('db') or ''))
    if not db or not os.path.isfile(db):
        return {}
    try:
        con = sqlite3.connect(f'file:{db}?immutable=1', uri=True)
        try:
            got = con.execute("SELECT name, value FROM settings WHERE name LIKE 'row_rules.row_%'").fetchall()
        finally:
            con.close()
    except sqlite3.Error:
        return {}
    out = {}
    for name, value in got:
        m = re.fullmatch(r'row_rules\.row_(\d{3})', str(name))
        try:
            v = json.loads(value)
        except (TypeError, ValueError):
            continue
        if m and isinstance(v, dict) and v.get('file') and v.get('rule'):
            out[v['file']] = {**v, 'row': int(m.group(1))}
    return out


def tune(text, row, name, office, origin=''):
    """HIS WORDS FINE TUNED BY HAND (TUNE), then his row's own number to the agent's name, then the original's office folder to this office's own."""
    for old, new in TUNE:
        text = re.sub(old, new, text)
    text = re.sub(rf'\brow {int(row):03d}\b', name, text)
    if origin:
        for a in (origin, origin.replace(os.path.expanduser('~'), '~', 1)):
            text = text.replace(a + os.sep, office + os.sep)
    return text


def detect(job, program):
    """THE LIE DETECTOR NOW (field 9), the program's hash against field 8: CLEAN when they match, DRIFT when the program changed since, TAMPER
    when the program cannot be read or no code was kept."""
    have = kept(job)
    try:
        with open(program, 'rb') as fh:
            now = sha(fh.read())
    except OSError:
        return 'TAMPER'
    if not have:
        return 'TAMPER'
    return 'CLEAN' if have['sha'] == now else 'DRIFT'


