    word = rules_word(job)   # THE HEAD SAYS THE REVIEW'S VERDICT, LEGIT or STUPID (the owner 2026-10-27: "AGENT001_SCRUM_MASTER_2.PY · CLEAN / we do not have a fucking clean status / LEGIT or STUPID only"), NOT READ YET before a read
